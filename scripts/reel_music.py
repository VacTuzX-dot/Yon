RATE = 44100
DUR = float(TL["duration"])
N = int(round(DUR * RATE))
BEAT = 60.0 / float(TL["bpm"])  # 0.6667 s
BAR = 4 * BEAT  # 2.6667 s
S16 = BEAT / 4  # 0.16667 s
BEAT_N = int(round(BEAT * RATE))  # 29400
TAU = 2 * math.pi
sin, cos, exp = math.sin, math.cos, math.exp
Rnd = random.Random

END_T = [float(c["t"]) for c in TL["cues"] if c["kind"] == "end"][0]  # 88.5
CHECK_T = [float(c["t"]) for c in TL["cues"] if c["kind"] == "check"][0]  # 52.0
CHORD_T = [float(c["t"]) for c in TL["cues"] if c["kind"] == "chord"][0]  # 87.333
DROP1 = [float(s["start"]) for s in TL["scenes"] if s["id"] == "sealed"][0]  # 37.333
BREATHER = [float(s["start"]) for s in TL["scenes"] if s["id"] == "breather"][0]  # 58.667
DROP2 = [float(s["start"]) for s in TL["scenes"] if s["id"] == "phones"][0]  # 66.667
OUTRO = [float(s["start"]) for s in TL["scenes"] if s["id"] == "outro"][0]  # 85.333


def at(t):
    return int(round(t * RATE))


def zeros(m):
    return array.array("d", bytes(8 * m))


def mtof(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def smooth(u):
    u = min(max(u, 0.0), 1.0)
    return u * u * (3 - 2 * u)


def pan_gains(p):
    p = min(max(p, 0.0), 1.0)
    return cos(p * math.pi / 2), sin(p * math.pi / 2)


def curve(points):
    def f(t):
        if t <= points[0][0]:
            return points[0][1]
        for (t0, v0), (t1, v1) in zip(points, points[1:]):
            if t <= t1:
                return v0 + (v1 - v0) * (t - t0) / (t1 - t0)
        return points[-1][1]

    return f


# ---------------------------------------------------------------- buses
padL, padR = zeros(N), zeros(N)
bassM = zeros(N)
dryL, dryR = zeros(N), zeros(N)
sendM = zeros(N)


def addto(buf, s, wav, g):
    if s < 0:
        wav = wav[-s:]
        s = 0
    m = min(len(wav), N - s)
    if m <= 0:
        return
    seg = buf[s:s + m]
    buf[s:s + m] = array.array("d", [a + b * g for a, b in zip(seg, wav)])


def mix(wav, t, gain, pan=0.5, send=0.0):
    """Add a mono waveform at time t (on the exact sample), fixed pan, optional delay send."""
    s = at(t)
    gl, gr = pan_gains(pan)
    addto(dryL, s, wav, gain * gl)
    addto(dryR, s, wav, gain * gr)
    if send:
        addto(sendM, s, wav, gain * send)


def mix_at(wav, s, gain, pan=0.5, send=0.0):
    """Same as mix() but with an explicit start sample."""
    gl, gr = pan_gains(pan)
    addto(dryL, s, wav, gain * gl)
    addto(dryR, s, wav, gain * gr)
    if send:
        addto(sendM, s, wav, gain * send)


def mix_moving(wav, t, gain, p0=0.5, p1=0.5, send=0.0, pf=None, s=None):
    """Mix with a pan that moves (linear p0 -> p1, or pf(u)); updated every 128 samples."""
    s = at(t) if s is None else s
    L = len(wav)
    B = 128
    for b0 in range(0, L, B):
        u = min(1.0, (b0 + B / 2) / L)
        p = pf(u) if pf else p0 + (p1 - p0) * u
        gl, gr = pan_gains(p)
        seg = wav[b0:b0 + B]
        addto(dryL, s + b0, seg, gain * gl)
        addto(dryR, s + b0, seg, gain * gr)
        if send:
            addto(sendM, s + b0, seg, gain * send)


def mix_bass(wav, t, gain):
    addto(bassM, at(t), wav, gain)


def fade_edges(w, attack_n=44, release_n=441):
    m = len(w)
    for j in range(min(attack_n, m)):
        w[j] *= j / attack_n
    for j in range(min(release_n, m)):
        w[m - 1 - j] *= j / release_n
    return w


def norm(w, peak=1.0):
    pk = max(max(w), -min(w)) or 1.0
    k = peak / pk
    return array.array("d", [x * k for x in w])


# ---------------------------------------------------------------- voices
_cache = {}


def pluck(midi, t60=1.2, bright=0.5):
    """Karplus-Strong string with an all-pass tuning filter."""
    key = ("pluck", midi, t60, bright)
    if key in _cache:
        return _cache[key]
    f = mtof(midi)
    r = Rnd(1000 + midi * 7 + int(bright * 100))
    total = RATE / f - 0.5
    P = int(total)
    frac = total - P
    if frac < 0.1:
        P -= 1
        frac += 1
    C = (1 - frac) / (1 + frac)
    loss = 10 ** (-3 / (t60 * f))
    noise = [r.uniform(-1, 1) for _ in range(P)]
    line = [0.0] * P
    s1 = 0.0
    for i in range(2 * P):
        s1 += bright * (noise[i % P] - s1)
        line[i % P] = s1
    mean = sum(line) / P
    peak = max(abs(x - mean) for x in line) or 1.0
    line = [(x - mean) / peak for x in line]
    m = int(min(3.0, t60 * 1.05) * RATE)
    out = zeros(m)
    prev = x1 = y1 = 0.0
    k = 0
    for n in range(m):
        s = line[k]
        out[n] = s
        avg = loss * 0.5 * (s + prev)
        prev = s
        y1 = C * avg + x1 - C * y1
        x1 = avg
        line[k] = y1
        k += 1
        if k == P:
            k = 0
    _cache[key] = fade_edges(out, 22, 1323)
    return _cache[key]


def tone(freq, seconds, partials=((1.0, 1.0),), attack=0.005, tau=0.5, glide_to=None, glide_s=0.0):
    """Additive sine tone with exponential decay and optional log-frequency glide."""
    key = ("tone", freq, seconds, partials, attack, tau, glide_to, glide_s)
    if key in _cache:
        return _cache[key]
    m = int(seconds * RATE)
    out = zeros(m)
    ph = 0.0
    inc = TAU * freq / RATE
    ea = 1.0 / max(1, attack * RATE)
    ed = exp(-1.0 / (tau * RATE))
    dec = 1.0
    gn = max(1, int(glide_s * RATE))
    ratio = (glide_to / freq) if glide_to else 1.0
    for n in range(m):
        if glide_to and n <= gn:
            inc = TAU * freq * ratio ** smooth(n / gn) / RATE
        v = 0.0
        for r, a in partials:
            v += a * sin(r * ph)
        ph += inc
        out[n] = v * min(1.0, n * ea) * dec
        dec *= ed
    _cache[key] = fade_edges(out, 1, 441)
    return _cache[key]


BELL_PARTS = ((1.0, 1.0, 1.0), (2.76, 0.42, 0.55), (5.4, 0.22, 0.32), (8.93, 0.1, 0.18))
GLASS_PARTS = ((1.0, 1.0, 1.0), (2.32, 0.6, 0.6), (4.25, 0.4, 0.4), (6.63, 0.25, 0.3), (9.38, 0.15, 0.2))


def bell(freq, seconds, tau, parts=BELL_PARTS):
    """Glassy bell: inharmonic partials, the upper ones dying faster."""
    key = ("bell", round(freq, 3), seconds, tau, parts)
    if key in _cache:
        return _cache[key]
    m = int(seconds * RATE)
    out = zeros(m)
    for r, a, dm in parts:
        if freq * r > 18000:
            continue
        inc = TAU * freq * r / RATE
        ed = exp(-1.0 / (tau * dm * RATE))
        d = a
        ph = 0.0
        for n in range(m):
            out[n] += sin(ph) * d
            ph += inc
            d *= ed
    for n in range(min(88, m)):
        out[n] *= n / 88
    _cache[key] = fade_edges(norm(out), 1, 441)
    return _cache[key]


def noise_sweep(seconds, fmin, fmax, cut_fn, amp_fn=None, rg=None, hp=0.0):
    """Filtered-noise whoosh: white noise through two one-pole low-passes whose
    cutoff follows cut_fn(u) in 0..1; amp_fn(u) is the loudness; optional high-pass."""
    rg = rg or Rnd(1)
    rnd = rg.random
    m = int(seconds * RATE)
    out = zeros(m)
    s1 = s2 = s3 = 0.0
    ahp = 1 - exp(-TAU * hp / RATE) if hp else 0.0
    B = 16
    c0 = cut_fn(0.0)
    e0 = amp_fn(0.0) if amp_fn else c0
    for b0 in range(0, m, B):
        b1 = min(b0 + B, m)
        c1 = cut_fn(b1 / m)
        e1 = amp_fn(b1 / m) if amp_fn else c1
        a = 1 - exp(-TAU * (fmin + (fmax - fmin) * c0) / RATE)
        de = (e1 - e0) / (b1 - b0)
        e = e0
        for n in range(b0, b1):
            x = rnd() * 2 - 1
            s1 += a * (x - s1)
            s2 += a * (s1 - s2)
            y = s2
            if ahp:
                s3 += ahp * (y - s3)
                y -= s3
            out[n] = y * e
            e += de
        c0, e0 = c1, e1
    return fade_edges(norm(out), 44, 441)


def hat_wave(seed, seconds, tau, hp=6000):
    r = Rnd(seed)
    m = int(seconds * RATE)
    out = zeros(m)
    a = 1 - exp(-TAU * hp / RATE)
    lp = 0.0
    for n in range(m):
        x = r.random() * 2 - 1
        lp += a * (x - lp)
        out[n] = (x - lp) * exp(-n / (tau * RATE))
    return fade_edges(norm(out), 22, 220)


def kick_wave(f_lo=48.0, f_hi=165.0, dec=0.15, drive=2.0, length=0.5):
    m = int(length * RATE)
    out = zeros(m)
    ph = 0.0
    for n in range(m):
        t = n / RATE
        ph += TAU * (f_lo + (f_hi - f_lo) * exp(-t / 0.02)) / RATE
        v = sin(ph) * exp(-t / dec)
        if n < 130:
            v += 0.45 * sin(TAU * 3100 * t) * exp(-t / 0.0015)
        out[n] = math.tanh(drive * v)
    return fade_edges(norm(out), 1, 441)


def sub_wave(f0, f1, seconds, tau, tc=0.3):
    """Sub boom: a sine falling f0 -> f1, long decay."""
    m = int(seconds * RATE)
    out = zeros(m)
    ph = 0.0
    for n in range(m):
        t = n / RATE
        ph += TAU * (f1 + (f0 - f1) * exp(-t / tc)) / RATE
        out[n] = (sin(ph) + 0.18 * sin(2 * ph)) * exp(-t / tau) * min(1.0, n / 110)
    return fade_edges(norm(out), 1, 882)


def clap_wave():
    r = Rnd(51)
    m = int(0.4 * RATE)
    out = zeros(m)
    a1 = 1 - exp(-TAU * 1000 / RATE)
    a2 = 1 - exp(-TAU * 6500 / RATE)
    lp1 = lp2 = 0.0
    bursts = (0.0, 0.011, 0.023, 0.036)
    for n in range(m):
        t = n / RATE
        x = r.random() * 2 - 1
        lp1 += a1 * (x - lp1)
        lp2 += a2 * ((x - lp1) - lp2)
        e = 0.0
        for h in bursts:
            if t >= h:
                e += exp(-(t - h) / 0.0045)
        e += 0.7 * exp(-max(0.0, t - 0.036) / 0.07) * (t >= 0.036)
        out[n] = lp2 * e
    return fade_edges(norm(out), 22, 441)


def snare_wave(seed=41, length=0.3, tau=0.065, body=185):
    r = Rnd(seed)
    m = int(length * RATE)
    out = zeros(m)
    a = 1 - exp(-TAU * 1800 / RATE)
    lp = ph = 0.0
    for n in range(m):
        t = n / RATE
        x = r.random() * 2 - 1
        lp += a * (x - lp)
        ph += TAU * (body + 120 * exp(-t / 0.02)) / RATE
        out[n] = (x - lp) * 0.75 * exp(-t / tau) + sin(ph) * 0.6 * exp(-t / 0.05)
    return fade_edges(norm(out), 22, 441)


def shaker_wave():
    r = Rnd(61)
    m = int(0.09 * RATE)
    out = zeros(m)
    a = 1 - exp(-TAU * 5000 / RATE)
    lp = 0.0
    for n in range(m):
        x = r.random() * 2 - 1
        lp += a * (x - lp)
        t = n / RATE
        out[n] = (x - lp) * min(1.0, t / 0.012) * exp(-t / 0.028)
    return fade_edges(norm(out), 22, 220)


def tom_wave(f0):
    m = int(0.35 * RATE)
    out = zeros(m)
    ph = 0.0
    for n in range(m):
        t = n / RATE
        ph += TAU * f0 * (1 + 0.7 * exp(-t / 0.03)) / RATE
        out[n] = (sin(ph) + (0.4 * sin(TAU * 3000 * t) * exp(-t / 0.002))) * exp(-t / 0.11)
    return fade_edges(norm(out), 1, 441)


SAW_SIZE = 2048


def saw_table(f):
    key = ("saw", round(f, 2))
    if key in _cache:
        return _cache[key]
    H = max(1, min(48, int(9000 / f)))
    tab = [0.0] * SAW_SIZE
    for h in range(1, H + 1):
        w = TAU * h / SAW_SIZE
        for i in range(SAW_SIZE):
            tab[i] += sin(w * i) / h
    pk = max(abs(v) for v in tab)
    tab = [v / pk for v in tab]
    _cache[key] = tab
    return tab


def bass_wave(midi, steps, level):
    """Sub sine + low-passed saw; level 0 (soft) .. 2 (heavy)."""
    key = ("bass", midi, steps, level)
    if key in _cache:
        return _cache[key]
    f = mtof(midi)
    tab = saw_table(f)
    secs = steps * S16 * 0.97 + 0.03
    m = int(secs * RATE)
    out = zeros(m)
    a = 1 - exp(-TAU * (180 + 520 * level + 3 * f) / RATE)
    lp = 0.0
    ph = 0.0
    inc = f / RATE * SAW_SIZE
    sp = 0.0
    sinc = TAU * f / RATE
    mixv = (0.0, 0.35, 0.6)[level]
    ed = exp(-1.0 / (0.5 * RATE))
    dec = 1.0
    for n in range(m):
        lp += a * (tab[int(ph) & (SAW_SIZE - 1)] - lp)
        ph += inc
        v = sin(sp) + mixv * lp * 1.6
        sp += sinc
        out[n] = v * dec * min(1.0, n / 180)
        dec *= ed
    if level == 2:
        out = array.array("d", [math.tanh(1.4 * x) for x in out])
    _cache[key] = fade_edges(norm(out), 1, 500)
    return _cache[key]


def lead_wave(midi, secs, sus=0.55, tau=0.25, lp_hz=3800):
    """Detuned saw pair, soft attack, exponential fall to a sustain."""
    key = ("lead", midi, round(secs, 3), sus, tau, lp_hz)
    if key in _cache:
        return _cache[key]
    f = mtof(midi)
    tab = saw_table(f)
    m = int(secs * RATE)
    out = zeros(m)
    i1 = f / RATE * SAW_SIZE
    i2 = i1 * 1.0046
    i3 = i1 * 0.9954
    p1, p2, p3 = 0.0, 611.0, 1303.0
    a = 1 - exp(-TAU * lp_hz / RATE)
    lp = 0.0
    ed = exp(-1.0 / (tau * RATE))
    dec = 1.0 - sus
    mask = SAW_SIZE - 1
    for n in range(m):
        v = tab[int(p1) & mask] + tab[int(p2) & mask] + tab[int(p3) & mask]
        p1 += i1
        p2 += i2
        p3 += i3
        lp += a * (v - lp)
        out[n] = lp * (sus + dec) * min(1.0, n / 260)
        dec *= ed
    _cache[key] = fade_edges(norm(out), 1, 700)
    return _cache[key]


def crush(w, hold=4, bits=4):
    lv = 2 ** (bits - 1)
    out = zeros(len(w))
    v = 0.0
    for j in range(len(w)):
        if j % hold == 0:
            v = round(w[j] * lv) / lv
        out[j] = v
    return fade_edges(out, 1, 220)


def rise_tone(d, f0, f1, pw=1.8, partials=((1.0, 1.0), (2.0, 0.3), (3.0, 0.12))):
    """Exponential pitch riser whose loudness grows as u**pw."""
    key = ("rise", d, f0, f1, pw, partials)
    if key in _cache:
        return _cache[key]
    m = int(d * RATE)
    out = zeros(m)
    ph = 0.0
    r = f1 / f0
    for n in range(m):
        u = n / m
        ph += TAU * f0 * r ** u / RATE
        v = 0.0
        for q, a in partials:
            v += a * sin(q * ph)
        out[n] = v * u ** pw
    _cache[key] = fade_edges(out, 44, 220)
    return _cache[key]


def tick_wave(seed, secs=0.02, tau=0.003, hp=2500):
    return hat_wave(seed, secs, tau, hp)


