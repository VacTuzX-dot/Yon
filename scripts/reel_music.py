PAD_SIZE = 4096
PAD_TAB = [sum(sin(h * TAU * i / PAD_SIZE) / h ** 1.7 for h in range(1, 8)) for i in range(PAD_SIZE)]
_pk = max(abs(v) for v in PAD_TAB)
