def s_whoosh(t, u, i):
    d = 2.3
    R = Rnd(760)
    spin = lambda x: 0.5 + 0.42 * sin(TAU * (0.9 * x * 2.3 + 2.4 * x * x * 2.3))
    env = lambda x: (x / 0.38) ** 2.4 if x < 0.38 else 1 - smooth((x - 0.38) / 0.62) * 0.97
    for k in range(2):
        w = noise_sweep(d, 150, 6500, env, rg=R, hp=120)
        mix_moving(w, t, 0.3, pf=(spin if k == 0 else (lambda x: 1 - spin(x))), send=0.2)
    mix(rise_tone(0.9, 200.0, 1600.0, pw=1.3), t, 0.12, 0.5, send=0.3)
    mix(tone(1600.0, 1.4, ((1.0, 1.0), (2.0, 0.15)), attack=0.01, tau=0.45, glide_to=520.0, glide_s=1.2), t + 0.9, 0.09, 0.5, send=0.4)


