def s_slam(t, u, i):
    big_hit(t, 1.15, sub=(70.0, 27.0), sub_tau=1.0, crash=True, tail=2.0, seed=20 + i)
    R = Rnd(600 + i)
    # distorted transient: noise + body through a hard tanh
    m = int(0.25 * RATE)
    dist = zeros(m)
    ph = 0.0
    for n in range(m):
        x = n / RATE
        ph += TAU * (60 + 260 * exp(-x / 0.02)) / RATE
        dist[n] = math.tanh(6.0 * (0.9 * sin(ph) + 0.6 * (R.random() * 2 - 1)) * exp(-x / 0.05))
    mix(fade_edges(norm(dist), 1, 441), t, 0.42, 0.5, send=0.12)
    mix(SNARE, t, 0.42, 0.5, send=0.25)
    mix(CLAP, t, 0.25, 0.5, send=0.3)
    # cards flying: a scatter of papery ticks
    for k in range(18):
        w = tick_wave(610 + k, R.choice((0.02, 0.03)), 0.005, R.uniform(1800, 5000))
        mix(w, t + 0.03 + k * R.uniform(0.012, 0.03), 0.16 * (1 - k / 22), R.uniform(0.05, 0.95))


