pad_cut = curve([(0, 300), (2, 300), (8, 900), (21.3333, 800), (37.0, 5200), (DROP1, 4200), (BREATHER - 0.1, 4200),
                 (BREATHER + 1.0, 1500), (65.0, 2000), (DROP2 - 0.05, 6000), (DROP2, 5200), (OUTRO, 5200),
                 (CHORD_T - 0.1, 450), (CHORD_T + 0.1, 6500), (DUR, 4500)])
duck_depth = curve([(0, 0.0), (21.3333, 0.0), (21.4, 0.22), (36.0, 0.32), (DROP1 - 0.01, 0.0), (DROP1, 0.58),
                    (BREATHER - 0.05, 0.58), (BREATHER, 0.0), (DROP2 - 0.01, 0.0), (DROP2, 0.58), (OUTRO - 0.02, 0.58), (OUTRO, 0.0)])
bass_gain = curve([(0, 1.0), (DUR, 1.0)])
FADE_S = DUR - END_T


def fade(t):
    if t >= DUR:
        return 0.0
    if t <= END_T:
        return 1.0
    return 0.5 * (1 + cos(math.pi * (t - END_T) / FADE_S))


DIP_LEN = int(0.3 * RATE)
DIP = [max(0.0, 1 - j / DIP_LEN) ** 1.7 for j in range(BEAT_N)]
D = int(round(0.75 * BEAT * RATE))  # dotted 8th ping-pong delay
FB, WET = 0.4, 0.55
a_damp = 1 - exp(-TAU * 2600 / RATE)
a_top = 1 - exp(-TAU * 12000 / RATE)
R_HP = exp(-TAU * 28 / RATE)
ringL, ringR = zeros(D), zeros(D)
outL, outR = zeros(N), zeros(N)
pl = pr = fl = fr = 0.0
xl1 = xr1 = hl = hr = ml = mr = 0.0
k = 0
for b0 in range(0, N, BLK):
    b1 = min(b0 + BLK, N)
    t = b0 / RATE
    ap = 1 - exp(-TAU * pad_cut(t) / RATE)
    pg = pad_level(t)
    dd = duck_depth(t)
    fd0, fd1 = fade(t), fade(b1 / RATE)
    dfd = (fd1 - fd0) / (b1 - b0)
    fd = fd0
    j = b0 % BEAT_N
    for n in range(b0, b1):
        pl += ap * (padL[n] - pl)
        pr += ap * (padR[n] - pr)
        dip = DIP[j]
        j += 1
        if j == BEAT_N:
            j = 0
        g = pg * (1 - dd * dip)
        gb = 1 - 0.85 * dd * dip
        wl = ringL[k]
        wr = ringR[k]
        fl += a_damp * (wl - fl)
        fr += a_damp * (wr - fr)
        sm_ = sendM[n]
        ringL[k] = sm_ * 0.8 + FB * fr
        ringR[k] = sm_ * 0.3 + FB * fl
        k += 1
        if k == D:
            k = 0
        bv = bassM[n] * gb
        xl = pl * g + bv + dryL[n] + WET * wl
        xr = pr * g + bv + dryR[n] + WET * wr
        hl = R_HP * (hl + xl - xl1)
        hr = R_HP * (hr + xr - xr1)
        xl1, xr1 = xl, xr
        ml += a_top * (hl - ml)
        mr += a_top * (hr - mr)
        outL[n] = ml * fd
        outR[n] = mr * fd
        fd += dfd

# ---- look-ahead peak limiter (64-sample blocks, 12-block look-ahead)
peak0 = max(max(outL), -min(outL), max(outR), -min(outR)) or 1.0
thr = 0.5 * peak0
LB = 64
nb = (N + LB - 1) // LB
req = []
for b in range(nb):
    sl = slice(b * LB, (b + 1) * LB)
    pk = max(max(outL[sl]), -min(outL[sl]), max(outR[sl]), -min(outR[sl]))
    req.append(min(1.0, thr / pk) if pk > 0 else 1.0)
LA = 12
tgt = [min(req[b:b + LA]) for b in range(nb)]
rel = 1 - exp(-LB / (0.12 * RATE))
gains = []
gcur = 1.0
for b in range(nb):
    if tgt[b] < gcur:
        gcur += (tgt[b] - gcur) * 0.45
        gcur = max(gcur, tgt[b]) if tgt[b] > gcur * 0.0 else gcur
    else:
        gcur += (tgt[b] - gcur) * rel
    gains.append(min(gcur, req[b]) if req[b] < gcur else gcur)
limL, limR = zeros(N), zeros(N)
gprev = 1.0
for b in range(nb):
    a0, a1 = b * LB, min((b + 1) * LB, N)
    g1 = gains[b]
    dg = (g1 - gprev) / (a1 - a0)
    ramp = [gprev + dg * (q + 1) for q in range(a1 - a0)]
    limL[a0:a1] = array.array("d", [x * y for x, y in zip(outL[a0:a1], ramp)])
    limR[a0:a1] = array.array("d", [x * y for x, y in zip(outR[a0:a1], ramp)])
    gprev = g1
limL[N - 1] = limR[N - 1] = 0.0

# gentle tanh for any leftover spikes, then peak-normalise to -1.5 dBFS
DRIVE = 1.15
peak = max(max(limL), -min(limL), max(limR), -min(limR)) or 1.0
knee = math.tanh(DRIVE)
fL = [math.tanh(DRIVE * x / peak) / knee for x in limL]
fR = [math.tanh(DRIVE * x / peak) / knee for x in limR]
peak2 = max(max(fL), -min(fL), max(fR), -min(fR)) or 1.0
scale = 10 ** (-1.5 / 20) * 32767 / peak2
pcm = array.array("h", bytes(4 * N))
pcm[0::2] = array.array("h", [round(x * scale) for x in fL])
pcm[1::2] = array.array("h", [round(x * scale) for x in fR])
if sys.byteorder == "big":
    pcm.byteswap()
