def s_buzz(t, u, i):
    r = Rnd(131)
    m = int(0.64 * RATE)
    car = zeros(m)
    rat = zeros(m)
    a1 = 1 - exp(-TAU * 1300 / RATE)
    a2 = 1 - exp(-TAU * 260 / RATE)
    lp1 = lp2 = ph = 0.0

    def pulse(tt, a, b):
        return smooth((tt - a) / 0.01) * (1 - smooth((tt - b + 0.03) / 0.03))

    for n in range(m):
        tt = n / RATE
        e = pulse(tt, 0.0, 0.24) + pulse(tt, 0.34, 0.58)
        am = 0.55 + 0.45 * sin(TAU * 52 * tt)
        x = r.random() * 2 - 1
        lp1 += a1 * (x - lp1)
        lp2 += a2 * (x - lp2)
        ph += TAU * (96 + 6 * sin(TAU * 9 * tt)) / RATE
        saw = sum(sin(h * ph) / h for h in range(1, 7))
        knock = 0.0
        for t0 in (0.0, 0.34):
            if tt >= t0:
                knock += sin(TAU * 170 * tt) * exp(-(tt - t0) / 0.02)
        car[n] = e * (am * saw * 0.5 + knock * 0.9)
        rat[n] = e * am * (lp1 - lp2)
    car, rat = norm(car), norm(rat)
    out = array.array("d", [0.65 * a + 0.45 * b for a, b in zip(car, rat)])
    mix(fade_edges(norm(out), 22, 441), t, 0.6, 0.4, send=0.08)


