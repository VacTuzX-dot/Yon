def s_relay(t, u, i):
    R = Rnd(720 + i)
    w = noise_sweep(1.1, 300, 4200, lambda x: smooth(x / 0.5) * (1 - 0.6 * smooth((x - 0.5) / 0.5)),
                    amp_fn=lambda x: math.sin(math.pi * x) ** 1.3, rg=R, hp=300)
    mix_moving(w, t, 0.3, 0.06, 0.94, send=0.2)
    # Doppler-like whistle: pitch drops as the packet passes the tower
    m = int(1.1 * RATE)
    wh = zeros(m)
    ph = 0.0
    for n in range(m):
        x = n / m
        f = 1500 - 650 * smooth((x - 0.35) / 0.3)
        ph += TAU * f / RATE
        wh[n] = sin(ph) * math.sin(math.pi * x) ** 2
    mix_moving(fade_edges(wh, 44, 441), t, 0.07, 0.06, 0.94, send=0.25)
    mix(tick_wave(730, 0.02, 0.004, 3500), t + 0.55, 0.4, 0.5)
    mix(bell(mtof((88, 91, 93)[i % 3]), 1.2, 0.3), t + 0.55, 0.22, 0.5, send=0.4)
    mix(pluck((57, 60, 64)[i % 3], 0.8, 0.45), t, 0.11, 0.1, send=0.25)
    mix(pluck((72, 76, 79)[i % 3], 0.8, 0.45), t + 1.0, 0.11, 0.9, send=0.25)


