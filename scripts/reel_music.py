def bwomp(f0, f1, secs, vib, vr=6.5):
    key = ("bwomp", f0, f1, secs, vib, vr)
    if key in _cache:
        return _cache[key]
    m = int(secs * RATE)
    out = zeros(m)
    ph = 0.0
    for n in range(m):
        x = n / m
        t = n / RATE
        f = f0 * (f1 / f0) ** smooth(x * 1.15) * (1 + vib * sin(TAU * vr * t))
        ph += TAU * f / RATE
        v = sin(ph) + 0.5 * sin(2 * ph) + 0.3 * sin(3 * ph) + 0.15 * sin(4 * ph)
        out[n] = v * min(1.0, n / 400) * exp(-t / (secs * 0.55))
    _cache[key] = fade_edges(norm(out), 1, 882)
    return _cache[key]


