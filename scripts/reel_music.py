def drums():
    sw = 0.09 * S16  # light shuffle on the odd 16ths
    for g in range(0, int(round(DUR / S16))):
        t = g * S16
        sec = section(t)
        if sec is None:
            continue
        if 36.0 <= t < DROP1:  # pre-drop: drums out, the roll takes over
            continue
        st = g % 16
        bar = g // 16
        bt, sub = divmod(st, 4)
        fl = 0.0 if sub else 1.0  # on a beat
        if sec == "intro":
            if st in (0, 8):
                mix(KICK_SOFT, t, 0.42 if g != 48 else 0.6, 0.5)
            if st in (2, 6, 10, 14):
                mix(HAT_C, t, 0.045, 0.6)
            if st in (4, 12) and bar >= 5:
                mix(SHAKER, t, 0.05, 0.4)
            continue
        if sec == "build":
            ramp = 0.75 + 0.25 * min(1.0, (bar - 8) / 5)
            if st in (0, 4, 8, 12) and bar >= 9:
                mix(KICK, t, 0.5 * ramp, 0.5)
            elif st in (0, 8) and bar == 8:
                mix(KICK_SOFT, t, 0.45, 0.5)
            if st in (4, 12):
                mix(CLAP, t, 0.17 * ramp, 0.52, send=0.2)
                mix(SNARE, t, 0.06 * ramp, 0.5)
            if st % 2 == 0:
                if st in (2, 6, 10, 14) and bar >= 10:
                    mix(HAT_O, t, 0.05, 0.62)
                else:
                    mix(HAT_C, t, 0.048 * (1.0 if st % 4 == 0 else 0.7), 0.4)
            elif bar >= 12:
                mix(HAT_C, t + sw, 0.025, 0.55)
            if st % 4 == 2:
                mix(SHAKER, t, 0.035, 0.35 + 0.3 * ((g // 4) % 2))
            continue
        # drop
        second = bar >= 25
        if st in (0, 4, 8, 12):
            mix(KICK, t, 0.62, 0.5)
        if second and st == 10 and bar >= 27:
            mix(KICK, t, 0.28, 0.5)
        if st in (4, 12):
            mix(CLAP, t, 0.24, 0.52, send=0.25)
