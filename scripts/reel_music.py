#!/usr/bin/env python3
"""Algorithmic soundtrack + sound effects for the 90 s launch reel (web/reel/).

Pure code, standard library only, fixed seeds: the same WAV byte for byte on
every run. No samples, nothing generated by a model. Bpm, scenes, cues and
stickerTimes are read from web/reel/timeline.json and every cue sound is
scheduled on the exact sample of its cue time.

    python3 scripts/reel_music.py web/reel/film.wav

Feel: 90 bpm (beat 0.6667 s, bar 2.6667 s), A minor (Am - F - C - G, one chord
per bar) with a bright A major lift at the check and at the final chord. Modern
keynote-reel energy: sine/saw sub bass, sidechain-pumped pad, plucked 16th
arps, a saw lead hook, 4-on-the-floor with claps and shuffled hats.

Sections (bars of 2.6667 s, all aligned to t = 0):
  0-2       digital silence
  2-8       wind swirl (music) + low A drone + ticking texture from 5.333
  8.0       impact, then a light beat (kick on 1 and 3, soft hats) to 21.33;
            the bass enters at 16
  21.33-37.33 build: 4-on-the-floor, claps on 2 and 4, bass line, 16th arps,
            the pad filter opens; snare rolls under the risers (25.33, 36)
  37.33-58.67 DROP: heavy sub bass, pumping pad, lead hook, full beat
  58.67-66.67 breather: no drums, soft pad, gentle keys, air; riser 65.33
  66.67-85.33 DROP 2: brighter, octave lead, extra percussion 74.67-80
  85.33-90  collapse, final A major chord at 87.333, fade 88.5 -> 90.0

Signal path: sources go to buses (pad stereo, bass mono, dry stereo, delay
send mono). One final pass: pad low-pass + sidechain duck, bass duck, dotted-8th
ping-pong delay, 28 Hz high-pass, 12 kHz top, master fade; then a look-ahead
peak limiter, a gentle tanh, and a normalise to -1.5 dBFS.
"""

