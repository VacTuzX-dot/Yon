def s_flutter(t, u, i):
    d = u - t
    R = Rnd(300)
    ticks = []
    for k in range(14):
        n = R.randint(150, 900)
        hp = R.uniform(1500, 5500)
        a = 1 - exp(-TAU * hp / RATE)
        lp = 0.0
        w = zeros(n)
        for j in range(n):
            x = R.random() * 2 - 1
            lp += a * (x - lp)
            w[j] = (x - lp) * exp(-j / (n * 0.28)) * min(1.0, j / 12)
        ticks.append(norm(w))
    tm = 0.0
    while tm < d - 0.02:
        x = tm / d
        env = smooth(x / 0.25) * (1 - smooth((x - 0.82) / 0.18))
        w = R.choice(ticks)
        mix(w, t + tm, 0.26 * env * R.uniform(0.25, 1.0), R.uniform(0.05, 0.95), send=0.06)
        tm += R.uniform(0.005, 0.026) * (1.25 - 0.6 * x)


