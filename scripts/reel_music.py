def render_pad():
    bounds = {0.0, DUR}
    for b in range(0, 34):
        bounds.add(b * BAR)
    for a, b, _ in OVERRIDES:
        bounds.add(a)
        bounds.add(min(b, DUR))
    pts = sorted(x for x in bounds if 2.0 - BAR <= x <= DUR)
    segs = []
    for i, t0 in enumerate(pts[:-1]):
        name = chord_name((t0 + pts[i + 1]) / 2)
        if segs and segs[-1][2] == name:
            segs[-1][1] = pts[i + 1]
        else:
            segs.append([t0, pts[i + 1], name])
    XF = 0.35
    for si, (t0, t1, name) in enumerate(segs):
        first, last = si == 0, si == len(segs) - 1
        a = max(2.0, t0 - (0 if first else XF / 2))
        b = t1 if last else t1 + XF / 2
        n0, n1 = at(a), min(N, at(b))
        if n1 <= n0:
            continue
        notes = CH[name][1]

        def env(t, t0=t0, t1=t1, first=first, last=last):
            e = 1.0
            if not first:
                e *= sin(math.pi / 2 * min(max((t - t0 + XF / 2) / XF, 0.0), 1.0))
            if not last:
                e *= cos(math.pi / 2 * min(max((t - t1 + XF / 2) / XF, 0.0), 1.0))
            return e

        for v, midi in enumerate(notes):
            f = mtof(midi)
            for side, det in enumerate((-0.0028, 0.0028)):
                inc = f * (1 + det) / RATE * PAD_SIZE
                ph = pad_rng.uniform(0, PAD_SIZE)
                gA, gB = (0.8, 0.3) if side == 0 else (0.3, 0.8)
                vol = 0.06 * (0.75 if midi > 70 else 1.0)
                rate = 0.06 + 0.021 * v
                lph = pad_rng.uniform(0, TAU)
                L, R = padL, padR
                g0 = vol * env(n0 / RATE) * (1 + 0.2 * sin(lph + TAU * rate * n0 / RATE))
