def chime(t, pan, extra=(), scale=1.0):
    """'Whole again': bright A-major chime (A5 C#6 E6) over A4."""
    for m in (69, 81, 85, 88) + tuple(extra):
        w = tone(mtof(m), 3.2, ((1.0, 1.0), (2.0, 0.22)), attack=0.004, tau=1.0)
        mix(w, t, (0.08 if m > 70 else 0.06) * scale, pan, send=0.35)


def stream(t0, t1, group=6):
    """Chunks leave the left device: groups of quick plucks, each rising in pitch
    and travelling left -> right."""
    k = 0
    while t0 + k * TRIP < t1 - 1e-9:
        t = t0 + k * TRIP
        pos = k % group
        pcs = {m % 12 for m in chord_at(t)[1]}
        pool = [m for m in range(60, 82) if m % 12 in pcs]
        m = pool[min(len(pool) - 1, pos + (k // group) % 3)]
        pan = 0.12 + 0.76 * pos / (group - 1)
        mix(pluck(m, 0.6, 0.5), t, 0.21 if pos else 0.25, pan, send=0.25)
        k += 1


def cascade(t0, t1, run=8, step=TRIP / 2):
    """The folder unfolds: falling runs of plucks, each run sweeping left -> right."""
    k = 0
    while t0 + k * step < t1 - 1e-9:
        t = t0 + k * step
        pos = k % run
        pcs = {m % 12 for m in chord_at(t)[1]}
        pool = [m for m in range(57, 86) if m % 12 in pcs]
        top = len(pool) - 1 - (k // run) % 3
        m = pool[max(0, top - pos)]
        pan = 0.15 + 0.7 * pos / (run - 1)
        mix(pluck(m, 0.5, 0.5), t, 0.21 if pos == 0 else 0.15, pan, send=0.3)
        k += 1


def toss(t0, seconds=2.5, step=0.1):
    """A short toss across the room: quick plucks L -> R climbing to an apex and
    falling again, like the arc of a thrown file."""
    pool = [m for m in range(64, 89) if m % 12 in (9, 0, 2, 4, 7)]  # A minor pentatonic
    n = int(seconds / step)
    half = (n - 1) / 2
    for k in range(n):
        arc = 1 - ((k - half) / half) ** 2
        m = pool[min(len(pool) - 1, int(round(arc * (len(pool) - 1) * 0.8)))]
        mix(pluck(m, 0.5, 0.5), t0 + k * step, 0.17 if k == 0 else 0.125, 0.12 + 0.76 * k / (n - 1), send=0.25)


def qr(t, seconds=1.0):
    """QR code forms on the floor: blips on a 50 ms grid, on/off like QR modules,
    panned like a scan line."""
    steps = int(round(seconds / 0.05))
    notes = (81, 84, 86, 88)  # A5 C6 D6 E6
    for i in range(steps):
        bit = i == 0 or rng.random() < 0.55
        if not bit:
            continue
        m = rng.choice(notes)
        w = tone(mtof(m), 0.09, ((1.0, 1.0), (3.0, 0.12), (5.0, 0.04)), attack=0.002, tau=0.022)
        mix(w, t + i * 0.05, 0.22, 0.2 + 0.6 * i / (steps - 1), send=0.15)


def scan(t):
    """The phone scans the code: a rising sweep travelling across the field,
    ending in a two-note confirm."""
