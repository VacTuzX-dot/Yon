def buzz(t):
    """Phone vibrating on a wooden desk: two short pulses of a low buzz, a
    band-passed rattle, and a knock at the start of each pulse."""
    r = random.Random(131)
    m = int(0.64 * RATE)
    car = zeros(m)
    rat = zeros(m)
    a1 = 1 - exp(-TAU * 1300 / RATE)
    a2 = 1 - exp(-TAU * 260 / RATE)
    lp1 = lp2 = ph = 0.0

    def pulse(tt, a, b):
        return smooth((tt - a) / 0.01) * (1 - smooth((tt - b + 0.03) / 0.03))

    for n in range(m):
        tt = n / RATE
        e = pulse(tt, 0.0, 0.24) + pulse(tt, 0.34, 0.58)
        am = 0.55 + 0.45 * sin(TAU * 52 * tt)  # the vibration itself
        x = r.uniform(-1, 1)
        lp1 += a1 * (x - lp1)
        lp2 += a2 * (x - lp2)
        ph += TAU * (96 + 6 * sin(TAU * 9 * tt)) / RATE
        saw = sum(sin(h * ph) / h for h in range(1, 7))
        knock = 0.0
        for t0 in (0.0, 0.34):
            if tt >= t0:
                knock += sin(TAU * 170 * tt) * exp(-(tt - t0) / 0.02)
        car[n] = e * (am * saw * 0.5 + knock * 0.9)
        rat[n] = e * am * (lp1 - lp2)
    peak_normalise(car)
    peak_normalise(rat)
    out = zeros(m)
    for n in range(m):
        out[n] = 0.65 * car[n] + 0.45 * rat[n]
    fade_edges(peak_normalise(out), 22, 441)
    mix(out, t, 0.42, 0.4, send=0.1)


