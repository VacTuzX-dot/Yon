def msg_out(t):
    """Message sent: a rising noise swoosh and a gliding sine, left -> right."""
    w = noise_sweep(0.5, 400, 4500, lambda u: smooth(u / 0.7) * (1 - smooth((u - 0.7) / 0.3)))
    mix_moving(w, t, 0.25, 0.3, 0.85, send=0.2)
    g = tone(mtof(76), 0.4, ((1.0, 1.0), (2.0, 0.15)), attack=0.01, tau=0.14, glide_to=mtof(88), glide_s=0.22)
    mix_moving(g, t, 0.15, 0.35, 0.8, send=0.25)


def whoosh(t, seconds, lo, hi, peak, gain):
    """Camera move: filtered noise that swells to `peak` (fraction of the length)
    and a sine riser underneath."""

    def env(u):
        if u < peak:
            return (u / peak) ** 2.4
        return 1.0 - smooth((u - peak) / (1 - peak)) * 0.97

    w = noise_sweep(seconds, 150, 5000, env)
    mix_moving(w, t, gain, 0.35, 0.65, send=0.2)
    r = tone(lo, seconds, ((1.0, 1.0), (2.0, 0.2)), attack=seconds * peak * 0.9, tau=60.0, glide_to=hi, glide_s=seconds * peak)
    mix(r, t, gain * 0.5, 0.5, send=0.25)


SPK_POOL = [81, 84, 86, 88, 91, 93, 96, 98]  # A5 C6 D6 E6 G6 A6 C7 D7


def spark_wave(m, crushed):
    key = ("spark", m, crushed)
    if key not in _cache:
        w = tone(mtof(m), 0.16, ((1.0, 1.0), (2.0, 0.35), (3.0, 0.18)), attack=0.001, tau=0.035)
        _cache[key] = crush(w, 4, 4) if crushed else w
    return _cache[key]


def sparkle(t, n, step, gain, crushed=False, asc=True):
    """A glitter of quick high notes (A minor pentatonic), rising or falling."""
    for i in range(n):
        u = i / (n - 1)
        idx = round((u if asc else 1 - u) * (len(SPK_POOL) - 1)) + fx_rng.choice((-1, 0, 0, 1))
        m = SPK_POOL[min(max(idx, 0), len(SPK_POOL) - 1)]
        g = gain * ((0.6 + 0.4 * u) if asc else (1.0 - 0.5 * u))
        mix(spark_wave(m, crushed), t + i * step, g, fx_rng.uniform(0.15, 0.85), send=0.3)


def crackle(t, seconds, gain, d0, d1):
    """Bit-crushed noise ticks whose density goes from d0 to d1 (per 4 ms)."""
    k = 0
    while k * 0.004 < seconds:
        u = k * 0.004 / seconds
        if fx_rng.random() < d0 + (d1 - d0) * u:
            m = fx_rng.randint(24, 90)
            blip = zeros(m)
            v = 0.0
            for j in range(m):
                if j % 4 == 0:
                    v = round(fx_rng.uniform(-1, 1) * 3) / 3
                blip[j] = v * exp(-j / (m * 0.45))
            mix(blip, t + k * 0.004, gain * (1.0 - 0.6 * u), fx_rng.uniform(0.1, 0.9), send=0.1)
        k += 1


def wipe(t, asc):
    """Pixel dissolve: bit-crushed sparkle and crackle. Rising into the island,
    falling (softer) back into the room."""
    if asc:
        sparkle(t, 16, 0.032, 0.11, crushed=True, asc=True)
        crackle(t, 0.5, 0.1, 0.25, 0.6)
    else:
        sparkle(t, 14, 0.04, 0.1, crushed=True, asc=False)
        crackle(t, 0.6, 0.08, 0.5, 0.15)


def creak():
    """Wooden chest lid: a saw-like tone that slides up with a random wobble and
    a stick-slip amplitude flutter."""
    r = random.Random(77)
    m = int(0.75 * RATE)
    out = zeros(m)
    ph = jit = 0.0
    for n in range(m):
        u = n / m
        jit += 0.05 * (r.uniform(-1, 1) - jit)
        f = 140 + 120 * smooth(u) + 32 * jit
        ph += TAU * f / RATE
        v = sin(ph) + 0.6 * sin(2 * ph) + 0.45 * sin(3 * ph) + 0.3 * sin(4 * ph) + 0.2 * sin(5 * ph)
        am = 0.55 + 0.45 * sin(TAU * (17 + 10 * u) * n / RATE)
        env = smooth(u / 0.15) * (1 - smooth((u - 0.72) / 0.28))
        out[n] = v * am * env
    return fade_edges(peak_normalise(out), 44, 441)


