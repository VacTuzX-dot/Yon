#!/usr/bin/env python3
"""Algorithmic soundtrack for the 90 s explainer film (web/film/).

Pure code, standard library only, fixed seeds: the same WAV byte for byte on
every run. No samples, nothing generated by a model. The timeline (scenes,
bpm, cues) is read from web/film/timeline.json, and every cue sound is
scheduled on the exact sample of its cue time.

Key of A: A minor pentatonic for melody, A major for the "whole again" moments
and the ending. At 100 bpm a beat is 0.6 s and a bar 2.4 s; the groove is
anchored on the `groove` cue (21.0 s = beat 35), so its bars fall on
21.0 + 2.4 n and everything lilts on the 8th-note-triplet grid (0.2 s).

Sections (scene ids and cues from the timeline):
  open     room tone: a soft Am9 pad fades in from the `dawn` cue (a slow noise
           and mallet bloom) with three quiet plucks, like morning light.
  problem  wistful room texture (Am9 - Fmaj9 - Dm9 - Em7), a few sparse plucks.
           `think` = a light bubbly pop rising in pitch each time; `nope` = a
           soft, slightly comic, descending "bwomp-bwomp".
  friend   `buzz` = two short low rattles of a phone on a wooden desk; `chat` =
           a friendly two-note message chime; `whoosh` = noise and a sine riser
           as the camera dives into the screen; `wipe` = a glittery, bit-crushed
           pixel sparkle rising into the island.
  groove   from `groove` (21.0) to the second `wipe` (66.0): soft sine kick,
           noise hats and snare on the triplet shuffle, triangle-wave chip bass,
           a thin 12.5% pulse arpeggio, and a 25% pulse lead that is doubled by
           a Karplus-Strong pluck so it stays warm. The pad follows Am - F - C - G
           one chord per bar and ducks under the kick. Layers enter bar by bar:
             nearby   (21-31) kick, hats, bass, arpeggio; sonar `ping`s echo
                      across the stereo field and the third opens into a rising
                      arpeggio; the lead enters on the bar before `send`.
             send     (31-46) full beat; `handshake` two tones glide in from
                      opposite sides and meet on A; `lock` a click and a clunk;
                      `stream-start` quick plucks travelling left -> right; the
                      `check` lands on an A-major chime and chord.
             folders  (46-55) `chest` creak, thunk and sparkle; a cascade of
                      falling plucks sweeping left -> right; `check` chime.
             phones   (55-66) the beat thins out for `qr` (digital blips like QR
                      modules) and `scan` (a sweep that ends in a two-note
                      confirm); `relay` whooshes of sealed packets pass a tower
                      left -> right, each marked with plucks; the last `check`
                      holds A major into a snare roll and a crash on the wipe.
  decide   back in the room (`wipe` sparkle falls, `calm` = the beat has stopped:
           low A and a soft settling chord); `dialog` a soft UI pop; `click` a
           mouse click (down and up); `stream-start` a short toss, an arc of
           quick plucks L -> R; `check` chime; `jump` a rising "boing"; `chat`
           (from "me") a rising message-sent swoosh, unlike the received chime.
  outro    `whoosh` flies out of the window; `build` logo blocks land as ticks
           that accelerate up an A minor pentatonic ladder under a rising noise
           swell; `swell` a big warm A-major chord; sparse shimmer, then the
           master fades from `end` (88.0 s) to silence exactly at 90.0 s.

Signal path: sources mix into three stereo buses (pad, dry, delay send). A
single final pass low-passes and ducks the pad, runs a ping-pong feedback delay
(two triplet 8ths, damped) on the send bus, high-passes the sum at ~30 Hz,
tames the top with a gentle one-pole low-pass, applies the fade, and the whole
thing is normalised to -1.5 dBFS peak.

    python3 scripts/film_music.py web/film/film.wav
"""

import array
import json
import math
import os
import random
import sys
import time

import wave

T_START = time.time()
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
with open(os.path.join(ROOT, "web", "film", "timeline.json"), encoding="utf-8") as fh:
    TL = json.load(fh)

RATE = 44100
DUR = float(TL["duration"])
N = int(round(DUR * RATE))
BEAT = 60.0 / float(TL["bpm"])  # 0.6 s at 100 bpm
TRIP = BEAT / 3  # 8th-note triplet, 0.2 s
BAR = 4 * BEAT  # 2.4 s
BEAT_N = int(round(BEAT * RATE))
SCENE = {s["id"]: s for s in TL["scenes"]}
TAU = 2 * math.pi
sin, cos, exp = math.sin, math.cos, math.exp

# Separate generators so adding a sound in one place never reshuffles another.
rng = random.Random(90)  # musical choices (arp notes, pans, QR bits)
noise_rng = random.Random(11)  # whoosh / swell noise
pad_rng = random.Random(5)  # pad phases and breathing
fx_rng = random.Random(33)  # sparkle / crackle choices


def cue_times(kind):
    return [float(c["t"]) for c in TL["cues"] if c["kind"] == kind]


def at(t):
    """Seconds -> sample index (rounded, so a cue lands within half a sample)."""
    return int(round(t * RATE))


def zeros(m):
    return array.array("d", bytes(8 * m))


def mtof(m):
    return 440.0 * 2 ** ((m - 69) / 12)


def smooth(u):
    u = min(max(u, 0.0), 1.0)
    return u * u * (3 - 2 * u)


def pan_gains(p):
    """Equal-power pan, 0 = left ... 1 = right."""
    return cos(p * math.pi / 2), sin(p * math.pi / 2)


def curve(points):
    """Piecewise-linear automation through (time, value) points."""

    def f(t):
        if t <= points[0][0]:
            return points[0][1]
        for (t0, v0), (t1, v1) in zip(points, points[1:]):
            if t <= t1:
                return v0 + (v1 - v0) * (t - t0) / (t1 - t0)
        return points[-1][1]

    return f


def in_any(windows, t):
    return any(a <= t < b for a, b in windows)


# Key moments from the timeline.
G0 = cue_times("groove")[0]  # the beat starts (21.0)
WIPES = cue_times("wipe")
GEND = WIPES[-1]  # the groove ends on the second pixel wipe (66.0)
CALM = cue_times("calm")[0]
END_T = cue_times("end")[0]
CHK = cue_times("check")
CHAT_FROM = {round(float(c["t"]), 3): c["from"] for c in TL["chat"]}
NBARS = int(math.ceil((GEND - G0) / BAR - 1e-9))  # 19, the last one is partial
S = {k: (float(v["start"]), float(v["end"])) for k, v in SCENE.items()}


# ---------------------------------------------------------------- buses
padL, padR = zeros(N), zeros(N)
dryL, dryR = zeros(N), zeros(N)
sendL, sendR = zeros(N), zeros(N)


def mix(wav, t, gain, pan=0.5, send=0.0):
    """Add a mono waveform at time t with a fixed pan (and delay send)."""
    s = at(t)
    m = min(len(wav), N - s)
    if m <= 0:
        return
    gl, gr = pan_gains(pan)
    gl *= gain
    gr *= gain
    dl, dr = dryL, dryR
    if send:
        sl, sr = gl * send, gr * send
        el, er = sendL, sendR
        for j in range(m):
            v = wav[j]
            n = s + j
            dl[n] += v * gl
            dr[n] += v * gr
            el[n] += v * sl
            er[n] += v * sr
    else:
        for j in range(m):
            v = wav[j]
            n = s + j
            dl[n] += v * gl
            dr[n] += v * gr


def mix_moving(wav, t, gain, pan0, pan1, send=0.0):
    """Like mix(), but the pan travels from pan0 to pan1 (updated every 64 samples)."""
    s = at(t)
    m = min(len(wav), N - s)
    for b0 in range(0, m, 64):
        gl, gr = pan_gains(pan0 + (pan1 - pan0) * smooth(b0 / len(wav)))
        gl *= gain
        gr *= gain
        sl, sr = gl * send, gr * send
        for j in range(b0, min(b0 + 64, m)):
            v = wav[j]
            n = s + j
            dryL[n] += v * gl
            dryR[n] += v * gr
            if send:
                sendL[n] += v * sl
                sendR[n] += v * sr


def fade_edges(w, attack_n=44, release_n=441):
    """Tiny linear fades so no waveform starts or stops with a click."""
    m = len(w)
    for j in range(min(attack_n, m)):
        w[j] *= j / attack_n
    for j in range(min(release_n, m)):
        w[m - 1 - j] *= j / release_n
    return w


def peak_normalise(w):
    peak = max(max(w), -min(w)) or 1.0
    for n in range(len(w)):
        w[n] /= peak
    return w


# ---------------------------------------------------------------- voices
_cache = {}


def pluck(midi, t60=1.2, bright=0.5):
    """Karplus-Strong string with an all-pass tuning filter (so high notes stay
    in tune), cached per pitch/tone. t60 = seconds to fall 60 dB; bright = how
    much of the noise burst's top end survives the pre-filter."""
    key = ("pluck", midi, t60, bright)
    if key in _cache:
        return _cache[key]
    f = mtof(midi)
    r = random.Random(1000 + midi * 7 + int(bright * 100))
    total = RATE / f - 0.5  # the two-point average adds half a sample of delay
    P = int(total)
    frac = total - P
    if frac < 0.1:
        P -= 1
        frac += 1
    C = (1 - frac) / (1 + frac)
    loss = 10 ** (-3 / (t60 * f))  # per trip round the loop
    noise = [r.uniform(-1, 1) for _ in range(P)]
    line = [0.0] * P
    s1 = 0.0
    for i in range(2 * P):  # two passes: the filter state wraps round the loop
        s1 += bright * (noise[i % P] - s1)
        line[i % P] = s1
    mean = sum(line) / P
    peak = max(abs(x - mean) for x in line) or 1.0
    line = [(x - mean) / peak for x in line]
    m = int(min(3.0, t60 * 1.05) * RATE)
    out = zeros(m)
    prev = x1 = y1 = 0.0
    k = 0
    for n in range(m):
        s = line[k]
        out[n] = s
        avg = loss * 0.5 * (s + prev)
        prev = s
        y1 = C * avg + x1 - C * y1
        x1 = avg
        line[k] = y1
        k += 1
        if k == P:
            k = 0
    _cache[key] = fade_edges(out, 22, 1323)
    return _cache[key]


def tone(freq, seconds, partials=((1.0, 1.0),), attack=0.005, tau=0.5, glide_to=None, glide_s=0.0):
    """Additive sine tone: partials are (ratio, amplitude); exponential decay tau;
    optional log-frequency glide from freq to glide_to over glide_s seconds."""
    key = ("tone", freq, seconds, partials, attack, tau, glide_to, glide_s)
    if key in _cache:
        return _cache[key]
    m = int(seconds * RATE)
    out = zeros(m)
    ph = 0.0
    inc = TAU * freq / RATE
    ea = 1.0 / max(1, attack * RATE)
    ed = exp(-1.0 / (tau * RATE))
    dec = 1.0
    gn = max(1, int(glide_s * RATE))
    ratio = (glide_to / freq) if glide_to else 1.0
    for n in range(m):
        if glide_to and n <= gn:
            inc = TAU * freq * ratio ** smooth(n / gn) / RATE
        v = 0.0
        for r, a in partials:
            v += a * sin(r * ph)
        ph += inc
        out[n] = v * min(1.0, n * ea) * dec
        dec *= ed
    _cache[key] = fade_edges(out, 1, 441)
    return _cache[key]


def noise_sweep(seconds, fmin, fmax, env_fn):
    """Filtered-noise whoosh: white noise through two one-pole low-passes whose
    cutoff follows the envelope (brighter when louder)."""
    m = int(seconds * RATE)
    out = zeros(m)
    s1 = s2 = 0.0
    for n in range(m):
        e = env_fn(n / m)
        a = 1 - exp(-TAU * (fmin + (fmax - fmin) * e) / RATE)
        s1 += a * (noise_rng.uniform(-1, 1) - s1)
        s2 += a * (s1 - s2)
        out[n] = s2 * e
    return fade_edges(out, 44, 441)


def kick_wave():
    """Soft kick: a sine dropping 120 -> 44 Hz with a short round decay."""
    m = int(0.5 * RATE)
    out = zeros(m)
    ph = 0.0
    for n in range(m):
        t = n / RATE
        ph += TAU * (44 + 76 * exp(-t / 0.03)) / RATE
        out[n] = sin(ph) * min(1.0, n / 88) * exp(-t / 0.17)
    return fade_edges(out, 1, 441)


def hat_wave(seed, seconds, tau, hp=6000):
    """Noise hat: white noise minus its own low-pass (a high-pass at hp Hz)."""
    r = random.Random(seed)
    m = int(seconds * RATE)
    out = zeros(m)
    a = 1 - exp(-TAU * hp / RATE)
    lp = 0.0
    for n in range(m):
        x = r.uniform(-1, 1)
        lp += a * (x - lp)
        out[n] = (x - lp) * exp(-n / (tau * RATE))
    return fade_edges(peak_normalise(out), 22, 220)


def snare_wave():
    """Soft snare: high-passed noise plus a short falling sine body."""
    r = random.Random(41)
    m = int(0.3 * RATE)
    out = zeros(m)
    a = 1 - exp(-TAU * 1800 / RATE)
    lp = ph = 0.0
    for n in range(m):
        t = n / RATE
        x = r.uniform(-1, 1)
        lp += a * (x - lp)
        ph += TAU * (160 + 110 * exp(-t / 0.02)) / RATE
        out[n] = (x - lp) * 0.7 * exp(-t / 0.065) + sin(ph) * 0.6 * exp(-t / 0.05)
    return fade_edges(peak_normalise(out), 22, 441)


def pulse_table(f, duty, size=1024):
    """One cycle of a band-limited pulse wave (harmonics up to ~8 kHz, gently
    rolled off), as a wavetable with a guard sample."""
    key = ("pt", round(f, 3), duty)
    if key in _cache:
        return _cache[key]
    H = max(1, int(8000 / f))
    amps = [(2 / (math.pi * h)) * sin(math.pi * h * duty) / (1 + (h * f / 6000) ** 2) for h in range(1, H + 1)]
    tab = [0.0] * (size + 1)
    for i in range(size):
        th = TAU * i / size
        tab[i] = sum(a * cos((h + 1) * th) for h, a in enumerate(amps))
    tab[size] = tab[0]
    peak = max(abs(v) for v in tab) or 1.0
    tab = [v / peak for v in tab]
    _cache[key] = tab
    return tab


def chip(midi, seconds, duty=0.25, tau=0.3, attack=0.004, vib=0.0):
    """Chiptune-style pulse voice (band-limited so it never aliases harshly):
    exponential decay, optional delayed vibrato."""
    key = ("chip", midi, seconds, duty, tau, attack, vib)
    if key in _cache:
        return _cache[key]
    f = mtof(midi)
    tab = pulse_table(f, duty)
    size = len(tab) - 1
    m = int(seconds * RATE)
    out = zeros(m)
    p = 0.0
    inc = f / RATE
    ea = 1.0 / max(1, attack * RATE)
    ed = exp(-1.0 / (tau * RATE))
    dec = 1.0
    vd = int(0.12 * RATE)
    vr = int(0.25 * RATE)
    for n in range(m):
        if vib and n > vd:
            inc = f * (1 + vib * min(1.0, (n - vd) / vr) * sin(TAU * 5.6 * (n - vd) / RATE)) / RATE
        x = p * size
        i = int(x)
        v = tab[i] + (tab[i + 1] - tab[i]) * (x - i)
        p += inc
        if p >= 1.0:
            p -= 1.0
        out[n] = v * min(1.0, n * ea) * dec
        dec *= ed
    _cache[key] = fade_edges(out, 1, 441)
    return _cache[key]


def tri_wave(midi, seconds, tau=0.2, attack=0.004):
    """Triangle voice for the chip bass."""
    key = ("tri", midi, seconds, tau, attack)
    if key in _cache:
        return _cache[key]
    m = int(seconds * RATE)
    out = zeros(m)
    inc = mtof(midi) / RATE
    p = 0.25  # start at the zero crossing
    ea = 1.0 / max(1, attack * RATE)
    ed = exp(-1.0 / (tau * RATE))
    dec = 1.0
    for n in range(m):
        out[n] = (4 * abs(p - 0.5) - 1) * min(1.0, n * ea) * dec
        p += inc
        if p >= 1.0:
            p -= 1.0
        dec *= ed
    _cache[key] = fade_edges(out, 1, 441)
    return _cache[key]


def crush(w, hold=4, bits=4):
    """Bit-crusher: sample-and-hold every `hold` samples, quantised to `bits`."""
    lv = 2 ** (bits - 1)
    out = zeros(len(w))
    v = 0.0
    for j in range(len(w)):
        if j % hold == 0:
            v = round(w[j] * lv) / lv
        out[j] = v
    return fade_edges(out, 1, 220)


