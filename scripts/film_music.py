def boing(t):
    """Happy little boing: the pitch springs upward, then a decaying wobble."""
    m = int(0.6 * RATE)
    out = zeros(m)
    ph = 0.0
    for n in range(m):
        tt = n / RATE
        f = 330 * (1 + 1.6 * (1 - exp(-tt / 0.06))) * (1 + 0.05 * sin(TAU * 15 * tt) * exp(-tt / 0.25))
        ph += TAU * f / RATE
        out[n] = (sin(ph) + 0.25 * sin(2 * ph)) * exp(-tt / 0.22) * min(1.0, n / 88)
    mix(fade_edges(out, 1, 441), t, 0.3, 0.5, send=0.2)
    mix(tone(mtof(93), 0.4, attack=0.002, tau=0.08), t + 0.1, 0.06, 0.55, send=0.3)


def build(t0, t1, count=32):
    """Logo blocks land: ticks that accelerate and climb an A minor pentatonic
    ladder, the last just before t1. Each is a short pitched blip and a wood tick."""
    ladder = [57, 60, 62, 64, 67, 69, 72, 74, 76, 79, 81, 84, 86, 88, 91, 93]
    wood = hat_wave(93, 0.03, 0.006, 1800)
    span = t1 - 0.25 - t0
    for k in range(count):
        x = k / (count - 1)
        t = t0 + span * (1 - (1 - x) ** 1.4)
        m = ladder[round(15 * x ** 0.9)]
        w = tone(mtof(m), 0.2, ((1.0, 1.0), (2.0, 0.3), (3.0, 0.1)), attack=0.001, tau=0.05)
        mix(w, t, 0.14 + 0.04 * x, 0.35 + 0.3 * ((k * 5) % 7) / 6, send=0.25)
        mix(wood, t, 0.08, 0.5)


