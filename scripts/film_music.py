FADE_S = DUR - END_T  # 2 s: from the end cue to silence at the last sample


def fade(t):
    if t >= DUR:
        return 0.0
    if t <= END_T:
        return 1.0
    return 0.5 * (1 + cos(math.pi * (t - END_T) / FADE_S))


DUCK = [min(1.0, j / 220) * exp(-j / (0.2 * RATE)) for j in range(BEAT_N)]
D = int(round(2 * TRIP * RATE))  # delay: two triplet 8ths = 0.4 s
FB, WET = 0.36, 0.55
a_damp = 1 - exp(-TAU * 2400 / RATE)
a_top = 1 - exp(-TAU * 11000 / RATE)
R_HP = exp(-TAU * 30 / RATE)
ringL, ringR = zeros(D), zeros(D)
outL, outR = zeros(N), zeros(N)
pl = pr = fl = fr = 0.0
xl1 = xr1 = hl = hr = ml = mr = 0.0
k = 0
for b0 in range(0, N, BLK):
    b1 = min(b0 + BLK, N)
    t = b0 / RATE
    ap = 1 - exp(-TAU * pad_cut(t) / RATE)
    pg = pad_gain(t)
    dd = duck_depth(t)
    fd0, fd1 = fade(t), fade(b1 / RATE)
    dfd = (fd1 - fd0) / (b1 - b0)
    fd = fd0
    j = b0 % BEAT_N
    for n in range(b0, b1):
        pl += ap * (padL[n] - pl)
        pr += ap * (padR[n] - pr)
        g = pg * (1 - dd * DUCK[j])
        j += 1
        if j == BEAT_N:
            j = 0
        wl = ringL[k]
        wr = ringR[k]
        fl += a_damp * (wl - fl)
        fr += a_damp * (wr - fr)
        ringL[k] = sendL[n] + FB * fr  # ping-pong: each side feeds the other
        ringR[k] = sendR[n] + FB * fl
        k += 1
        if k == D:
            k = 0
        xl = pl * g + dryL[n] + WET * wl
        xr = pr * g + dryR[n] + WET * wr
        hl = R_HP * (hl + xl - xl1)
        hr = R_HP * (hr + xr - xr1)
        xl1, xr1 = xl, xr
        ml += a_top * (hl - ml)
        mr += a_top * (hr - mr)
        outL[n] = ml * fd
        outR[n] = mr * fd
        fd += dfd
outL[N - 1] = outR[N - 1] = 0.0  # silent on the very last sample

# Soft-clip (tanh), then normalise to -1.5 dBFS peak and write 16-bit stereo.
# WHY: kick, stabs and chimes pile up into rare peaks ~14 dB over the average;
# a gentle tanh (linear for small signals) trims them so the beat sits louder
# while the peak still lands exactly on -1.5 dBFS.
DRIVE = 1.25
peak = max(max(outL), -min(outL), max(outR), -min(outR)) or 1.0
knee = math.tanh(DRIVE)
outL = [math.tanh(DRIVE * x / peak) / knee for x in outL]
outR = [math.tanh(DRIVE * x / peak) / knee for x in outR]
scale = 10 ** (-1.5 / 20) * 32767
pcm = array.array("h", bytes(4 * N))
pcm[0::2] = array.array("h", [round(x * scale) for x in outL])
pcm[1::2] = array.array("h", [round(x * scale) for x in outR])
if sys.byteorder == "big":
    pcm.byteswap()
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "web", "film", "film.wav")
with wave.open(out, "wb") as w:
    w.setnchannels(2)
    w.setsampwidth(2)
    w.setframerate(RATE)
    w.writeframes(pcm.tobytes())
