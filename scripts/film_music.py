pings = cue_times("ping")
arp(S["nearby"][0], S["nearby"][1], 0.35, 64, 79, 0.12, skip=[(p - 0.05, p + 0.25) for p in pings])
for i, p in enumerate(pings):
    ping(p, (76, 81, 81)[min(i, 2)], (0.28, 0.72, 0.5)[min(i, 2)])
ping(pings[-1], 76, 0.5, gain=0.09)  # the third ping is a dyad ...
for j, m in enumerate((76, 81, 84, 88)):  # ... and the devices light up
    mix(pluck(m, 1.2, 0.5), pings[-1] + (j + 1) * TRIP, 0.09, 0.35 + 0.1 * j, send=0.35)

# send: pulse, handshake, stream, check
streams = cue_times("stream-start")
st_send = [t for t in streams if scene_at(t) == "send"][0]
st_fold = [t for t in streams if scene_at(t) == "folders"][0]
st_phone = [t for t in streams if scene_at(t) == "phones"][0]
hs = cue_times("handshake")[0]
handshake(hs)
arp(S["send"][0], st_send, 0.3, 64, 79, 0.1, skip=[(hs - 0.05, hs + 1.2)])
stream(st_send, CHECKS[0] - 2 * TRIP)
chime(CHECKS[0], 0.65)
arp(CHECKS[0] + 2 * TRIP, S["send"][1], 0.25, 64, 79, 0.09)

# the pulse: kick every beat from the send scene until the open scene
KICK = kick_wave()
kick_gain = curve([(S["send"][0], 0.2), (S["send"][0] + 2.4, 0.5), (S["folders"][0], 0.6),
                   (S["phones"][0], 0.45), (S["open"][0], 0.45)])
kb = math.ceil(S["send"][0] / BEAT - 1e-9)
while kb * BEAT < S["open"][0] - 1e-9:
    t = kb * BEAT
    mix(KICK, t, kick_gain(t), 0.5)
    kb += 1

# bass: plucked root on the beat and on the last triplet, from the handshake on
bass_gain = curve([(hs, 0.13), (S["folders"][0], 0.17), (S["phones"][0], 0.13), (S["open"][0], 0.13)])
kb = math.ceil(hs / BEAT - 1e-9)
while kb * BEAT < S["open"][0] - 1e-9:
    t = kb * BEAT
    root = chord_at(t + 0.01)[0]
    w = tone(mtof(root), 0.55, ((1.0, 1.0), (2.0, 0.3), (3.0, 0.06)), attack=0.008, tau=0.28)
    mix(w, t, bass_gain(t), 0.5)
    mix(w, t + 2 * TRIP, bass_gain(t) * 0.45, 0.5)
    kb += 1

# folders: ticks, cascade, check
TICKS = [tick_wave(s) for s in (1, 2, 3)]
kb = math.ceil(S["folders"][0] / TRIP - 1e-9)
while kb * TRIP < S["open"][0] - 1e-9:
    t = kb * TRIP
    slot = kb % 3
    sc = scene_at(t)
    if slot and (sc == "folders" or (sc == "phones" and t >= st_phone and slot == 2)):
        g = (0.035 if slot == 2 else 0.018) * (1.0 if sc == "folders" else 0.6)
        mix(TICKS[kb % 3], t, g, 0.42 if slot == 1 else 0.58)
    kb += 1
arp(S["folders"][0], st_fold, 0.5, 64, 81, 0.1)
cascade(st_fold, CHECKS[1] - 3 * TRIP)
chime(CHECKS[1], 0.7, extra=(76,))
arp(CHECKS[1] + 2 * TRIP, S["folders"][1], 0.4, 64, 81, 0.09)

# phones: QR blips, sealed blobs past the relay
q = cue_times("qr")[0]
arp(S["phones"][0], st_phone, 0.3, 64, 79, 0.09, skip=[(q - 0.1, q + 2.0)])
qr(q)
blobs(st_phone, S["phones"][1] - 0.4)

# open: resolve, low A, logo swell, fade by the end cue
mix(tone(mtof(45), 8.0, ((1.0, 1.0), (2.0, 0.3)), attack=0.06, tau=3.0), S["open"][0], 0.16, 0.5)
end_t = cue_times("end")[0]
sw2 = cue_times("swell")[-1]
arp(S["open"][0] + 2 * TRIP, sw2 - 0.4, 0.3, 69, 84, 0.08)
swell(sw2, 2.0, 5.0, (57, 61, 64, 69, 76), 0.11)
arp(sw2 + 1.0, end_t - 1.5, 0.18, 69, 84, 0.06, t60=1.8)

# ---------------------------------------------------------------- final pass
pad_gain = curve([(0, 0.0), (3.0, 1.0), (S["send"][0], 1.0), (S["send"][0] + 2, 0.9),
                  (S["folders"][0], 1.0), (S["phones"][0], 0.9), (S["open"][0], 1.05)])
pad_cut = curve([(0, 700), (8, 1100), (S["nearby"][0], 1200), (S["send"][0], 1500),
                 (S["folders"][0], 2300), (S["phones"][0], 1700), (S["open"][0], 2200), (DUR, 1500)])
duck_depth = curve([(S["send"][0], 0.0), (S["send"][0] + 2.4, 0.28), (S["folders"][0], 0.38),
                    (S["phones"][0], 0.28), (S["open"][0] - 0.2, 0.28), (S["open"][0] + 0.4, 0.0)])
FADE_S = 4.0


def fade(t):
    if t >= end_t:
        return 0.0
    if t <= end_t - FADE_S:
        return 1.0
    return 0.5 * (1 + cos(math.pi * (t - end_t + FADE_S) / FADE_S))


DUCK = [min(1.0, j / 220) * exp(-j / (0.2 * RATE)) for j in range(BEAT_N)]
D = int(round(2 * TRIP * RATE))  # delay: two triplet 8ths = 0.4 s
FB, WET = 0.36, 0.55
a_damp = 1 - exp(-TAU * 2400 / RATE)
a_top = 1 - exp(-TAU * 11000 / RATE)
R_HP = exp(-TAU * 30 / RATE)
ringL, ringR = zeros(D), zeros(D)
outL, outR = zeros(N), zeros(N)
pl = pr = fl = fr = 0.0
xl1 = xr1 = hl = hr = ml = mr = 0.0
k = 0
for b0 in range(0, N, BLK):
    b1 = min(b0 + BLK, N)
    t = b0 / RATE
    ap = 1 - exp(-TAU * pad_cut(t) / RATE)
    pg = pad_gain(t)
    dd = duck_depth(t)
    fd0, fd1 = fade(t), fade(b1 / RATE)
    dfd = (fd1 - fd0) / (b1 - b0)
    fd = fd0
    j = b0 % BEAT_N
    for n in range(b0, b1):
        pl += ap * (padL[n] - pl)
        pr += ap * (padR[n] - pr)
        g = pg * (1 - dd * DUCK[j])
        j += 1
        if j == BEAT_N:
            j = 0
        wl = ringL[k]
        wr = ringR[k]
        fl += a_damp * (wl - fl)
        fr += a_damp * (wr - fr)
        ringL[k] = sendL[n] + FB * fr  # ping-pong: each side feeds the other
        ringR[k] = sendR[n] + FB * fl
        k += 1
        if k == D:
            k = 0
        xl = pl * g + dryL[n] + WET * wl
        xr = pr * g + dryR[n] + WET * wr
        hl = R_HP * (hl + xl - xl1)
        hr = R_HP * (hr + xr - xr1)
        xl1, xr1 = xl, xr
        ml += a_top * (hl - ml)
        mr += a_top * (hr - mr)
        outL[n] = ml * fd
        outR[n] = mr * fd
        fd += dfd

# Normalise to -1.5 dBFS peak and write 16-bit stereo.
peak = max(max(outL), -min(outL), max(outR), -min(outR)) or 1.0
scale = 10 ** (-1.5 / 20) * 32767 / peak
pcm = array.array("h", bytes(4 * N))
pcm[0::2] = array.array("h", [round(x * scale) for x in outL])
pcm[1::2] = array.array("h", [round(x * scale) for x in outR])
if sys.byteorder == "big":
    pcm.byteswap()
out = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "web", "film", "film.wav")
with wave.open(out, "wb") as w:
    w.setnchannels(2)
    w.setsampwidth(2)
    w.setframerate(RATE)
    w.writeframes(pcm.tobytes())
print(f"wrote {out}: {N / RATE:.3f}s, {RATE} Hz 16-bit stereo, {time.time() - T_START:.1f}s to render")
